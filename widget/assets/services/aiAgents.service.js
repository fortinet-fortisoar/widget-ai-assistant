'use strict';

(function () {
    angular
        .module('cybersponse')
        .factory('aiAgentsService', aiAgentsService);

    aiAgentsService.$inject = ['$q', '$http'];

    function aiAgentsService($q, $http) {
        var service;
        var _sessionId = '';
        const AGENT_API = `api/ai/agents/`;
        service = {
            insightChat: insightChat,
            agentConversation: agentConversation,
            pollAgentStatus: pollAgentStatus,
            conversationResult: conversationResult,
            tokenConsumption: tokenConsumption
        };

        /**
            * @ngdoc method
            * @name fortisoar.aiAgentsService#insightChat
            * @methodOf fortisoar.aiAgentsService
            *
            * @description
            * This method will return the insight chat
            *
            * @param {Object} param Object with user.uuid, insightThreadId, insight_id and user messages
            * @returns {Promise} A promise that will return the AI generated response to given params 
        **/
        function insightChat(param) {
            let defer = $q.defer();
            let queryUrl ='/api/ai/chat/';
            let queryParam = param;
                $http.post(queryUrl, queryParam).then(function (result) {
                    if (result) {
                        defer.resolve(result.data);
                    }
                },
                    function (error) {
                        if (error) {
                            defer.reject(error);
                        }
                    });
            return defer.promise;
        }

         function agentConversation(agent_name, param, sessionId) {
            let defer = $q.defer();
            let queryUrl =`${AGENT_API}${agent_name}/trigger`;
            let queryParam = param;
            _sessionId = sessionId;
            const headers = {
                                'X-CHAT-SESSION-ID': _sessionId
                            };
                $http.post(queryUrl, queryParam, {headers : headers}).then(function (result) {
                    if (result) {
                        defer.resolve(result.data);
                    }
                },
                    function (error) {
                        if (error) {
                            defer.reject(error);
                        }
                    });
            return defer.promise;
        }

        function pollAgentStatus(taskId) {
            let defer = $q.defer();
            let queryUrl =`${AGENT_API}${taskId}/status`;
                $http.get(queryUrl).then(function (result) {
                    if (result) {
                        defer.resolve(result.data);
                    }
                },
                    function (error) {
                        if (error) {
                            defer.reject(error);
                        }
                    });
            return defer.promise;
        }

        function conversationResult(taskId) {
            let defer = $q.defer();
            let queryUrl = `${AGENT_API}${taskId}/result`;
            $http.get(queryUrl).then(function (result) {
                if (result) {
                    defer.resolve(result.data);
                }
            },
                function (error) {
                    if (error) {
                        defer.reject(error);
                    }
                });
            return defer.promise;
        }

        /**
            * @ngdoc method
            * @name fortisoar.aiAgentsService#tokenConsumption
            * @methodOf fortisoar.aiAgentsService
            *
            * @description
            * Fetches the cumulative token usage for the active chat session.
            *
            * The session identifier is read from the service-level
            * `_sessionId`, which is populated by
            * {@link fortisoar.aiAgentsService#agentConversation `agentConversation`}
            * before the conversation begins.
            *
            * @returns {Promise<Object>} A promise that resolves with the token
            *   usage payload for the session. The payload contains:
            *   - `input_tokens`  {number} Tokens consumed by the prompt(s)
            *   - `output_tokens` {number} Tokens generated by the model
            *   - `total_tokens`  {number} Sum of input and output tokens
            *   - `llm_calls`     {number} Number of LLM invocations in the session
            *   The promise is rejected if the HTTP request fails.
            *
            * @requires $http
        **/
        function tokenConsumption() {
            let defer = $q.defer();
            // Send X-CHAT-SESSION-ID as a static header key (value is
            // empty) so the backend can attribute token usage to a chat
            // session.
            let queryUrl = `api/ai/traces/tokens/session/${_sessionId}`;
                $http.get(queryUrl).then(function (result) {
                    if (result) {
                        defer.resolve(result.data);
                    } else {
                        defer.reject('No token usage data returned');
                    }
                },
                    function (error) {
                        if (error) {
                            defer.reject(error);
                        }
                    });
            return defer.promise;
        }

        return service;
    }
})();
